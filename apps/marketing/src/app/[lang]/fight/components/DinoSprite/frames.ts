const normalize = (rows: string[]) =>
	rows.map((row) => row.slice(0, SPRITE_SIZE).padEnd(SPRITE_SIZE, "."));

const frame = (head: string[], legs: string[]) =>
	normalize([...head, ...TORSO, ...legs]);

